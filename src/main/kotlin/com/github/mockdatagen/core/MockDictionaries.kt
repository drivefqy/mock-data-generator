    /** 按品类编码取单个大类;「全部」/空/未知 返回 null */
    fun categoryOf(label: String?): ProductCategory? {
        val key = label?.trim().orEmpty()
        if (key.isEmpty() || key == ALL) return null
        return productCategories.firstOrNull { it.label == key }
    }

    /** 按品类编码取候选大类集合;「全部」/空/未知 返回全部 */
    fun categoriesOf(label: String?): List<ProductCategory> = categoryOf(label)?.let { listOf(it) } ?: productCategories

